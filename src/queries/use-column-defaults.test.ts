import { describe, expect, it } from 'vitest';
import type { ColumnInfo } from '@/api/types/structure.types';
import { hasGeneratedDefault } from './use-column-defaults';

const column = (
  defaultValue: string | null,
  isAutoGenerated = false,
): ColumnInfo => ({
  name: 'c',
  ordinal: 1,
  dataType: 'text',
  isNullable: true,
  defaultValue,
  isAutoGenerated,
  isPrimaryKey: false,
  isForeignKey: false,
});

describe('hasGeneratedDefault', () => {
  it.each([
    "nextval('users_id_seq'::regclass)",
    'now()',
    'gen_random_uuid()',
    'CURRENT_TIMESTAMP',
    "(datetime('now'))",
    'current_date',
  ])('expressão que gera valor: %s', expr => {
    expect(hasGeneratedDefault(column(expr))).toBe(true);
  });

  it.each(['true', '0', "'pendente'::text", "'{}'::text[]", "'-1'::integer"])(
    'constante não conta: %s',
    expr => {
      expect(hasGeneratedDefault(column(expr))).toBe(false);
    },
  );

  it('identity/rowid/_id sem DEFAULT declarado conta', () => {
    expect(hasGeneratedDefault(column(null, true))).toBe(true);
    expect(hasGeneratedDefault(column(null))).toBe(false);
  });
});
