import { useMemo } from 'react';
import type { EditableInfo } from '@/api/types/query.types';
import type { ColumnInfo } from '@/api/types/structure.types';
import { useColumns } from './use-columns';

const NONE: ReadonlySet<string> = new Set();

/** Palavras-chave de data/hora que valem como função sem parênteses */
const TIME_KEYWORD =
  /^\(?\s*(current_timestamp|current_date|current_time|localtimestamp|localtime)\b/i;

/**
 * O banco gera um valor novo a cada linha: serial/identity, rowid, `_id`, ou
 * um default que é expressão (`nextval(…)`, `now()`, `gen_random_uuid()`,
 * `CURRENT_TIMESTAMP`). Default constante (`true`, `0`, `'pendente'::text`)
 * não conta: deixá-lo para o banco trocaria o valor da linha pelo padrão.
 */
export function hasGeneratedDefault(column: ColumnInfo): boolean {
  if (column.isAutoGenerated) return true;
  const expr = column.defaultValue?.trim();
  if (!expr) return false;
  return /[\w"]\s*\(/.test(expr) || TIME_KEYWORD.test(expr);
}

/**
 * Colunas da tabela editável da grade cujo valor o banco gera (id, created_at,
 * uuid…). Duplicar e colar na mesma grade as deixam como DEFAULT, e a
 * exportação SQL pode omiti-las. Sem tabela (query livre), vazio.
 */
export function useColumnDefaults(
  serverId: number,
  database: string,
  editableInfo: EditableInfo | null | undefined,
): ReadonlySet<string> {
  const { data } = useColumns(
    editableInfo
      ? {
          serverId,
          database,
          schema: editableInfo.schema,
          table: editableInfo.table,
        }
      : null,
  );

  return useMemo(
    () =>
      data
        ? new Set(data.filter(hasGeneratedDefault).map(column => column.name))
        : NONE,
    [data],
  );
}
